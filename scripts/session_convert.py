def codex_to_claude(src, out_path=None, install=True, include_context=False,
                    reasoning_mode="thinking", title=None, override_cwd=None,
                    on_conflict="skip"):
    records = read_jsonl(src)

    meta = next((r["payload"] for r in records if r.get("type") == "session_meta"), {})
    cwd = override_cwd or meta.get("cwd", os.getcwd())
    session_id = meta.get("session_id") or meta.get("id") or str(uuid.uuid4())

    project_dir = os.path.join(CLAUDE_PROJECTS_DIR, sanitize_project_dir(cwd))
    if install and out_path is None:
        out_path = os.path.join(project_dir, session_id + ".jsonl")
        out_path, fork_id, skipped = _resolve_output_conflict(
            out_path, on_conflict, lambda: str(uuid.uuid4()),
            lambda target_id: os.path.join(project_dir, target_id + ".jsonl"))
        if skipped:
            return out_path
        if fork_id:
            session_id = fork_id
    elif out_path is not None:
        out_path, fork_id, skipped = _resolve_output_conflict(
            out_path, on_conflict, lambda: str(uuid.uuid4()))
        if skipped:
            return out_path
        if fork_id:
            session_id = fork_id

    out = []
    parent_uuid = None
    prompt_id = str(uuid.uuid4())
    first_user_text = None
    # 同一个 codex 回合里的连续 assistant 块共享一个 message id
    cur_msg_id = None
    # Codex 会在每次恢复会话时重复记录未回答的用户输入, 用于去重
    last_human_text = None

    def base_fields(ts):
        return {
            "parentUuid": parent_uuid,
            "isSidechain": False,
            "userType": "external",
            "cwd": cwd,
            "sessionId": session_id,
            "version": CLAUDE_VERSION,
            "gitBranch": "",
            "timestamp": ts,
        }

    def emit_user(ts, content, is_human):
        nonlocal parent_uuid, cur_msg_id
        rec = base_fields(ts)
        rec.update({
            "type": "user",
            "promptId": prompt_id,
            "message": {"role": "user", "content": content},
            "uuid": str(uuid.uuid4()),
        })
        if is_human:
            rec["origin"] = {"kind": "human"}
        out.append(rec)
        parent_uuid = rec["uuid"]
        cur_msg_id = None  # 新一轮, 下个 assistant 块用新 message id

    def emit_assistant(ts, block):
        nonlocal parent_uuid, cur_msg_id
        if cur_msg_id is None:
            cur_msg_id = "msg_conv_" + uuid.uuid4().hex[:24]
        rec = base_fields(ts)
        rec.update({
            "type": "assistant",
            "message": {
                "model": meta.get("model", "converted-from-codex"),
                "id": cur_msg_id,
                "type": "message",
                "role": "assistant",
                "content": [block],
                "stop_reason": None,
                "stop_sequence": None,
                "usage": {"input_tokens": 0, "output_tokens": 0},
            },
            "uuid": str(uuid.uuid4()),
        })
        out.append(rec)
        parent_uuid = rec["uuid"]

    for rec in records:
        if rec.get("type") != "response_item":
            continue
        p = rec.get("payload", {})
        pt = p.get("type")
        ts = rec.get("timestamp") or now_iso()

        if pt == "message":
            role = p.get("role")
            text = content_to_text(p.get("content"))
            images = content_images(p.get("content")) if role == "user" else []
            if not text.strip() and not images:
                continue
            if role == "user":
                stripped = text.lstrip()
                if not include_context and stripped.startswith(CONTEXT_PREFIXES):
                    continue
                if not images and text.strip() == last_human_text:
                    continue  # 恢复会话时重复记录的同一条输入(可能差个换行)
                last_human_text = text.strip()
                prompt_id = str(uuid.uuid4())
                if first_user_text is None and text.strip():
                    first_user_text = text
                if images:
                    blocks = [{"type": "image",
                               "source": {"type": "base64", "media_type": m,
                                          "data": d}} for m, d in images]
                    if text.strip():
                        blocks.append({"type": "text", "text": text})
                    emit_user(ts, blocks, is_human=True)
                else:
                    emit_user(ts, text, is_human=True)
            elif role == "assistant":
                last_human_text = None
                emit_assistant(ts, {"type": "text", "text": text})
            else:  # developer / system: 默认跳过
                if include_context:
                    emit_user(ts, "[%s context]\n%s" % (role, text), is_human=False)

        elif pt == "reasoning":
            if reasoning_mode == "skip":
                continue
            summary = "\n\n".join(
                s.get("text", "") for s in p.get("summary", []) if s.get("text")
            )
            if not summary.strip():
                continue
            if reasoning_mode == "text":
                emit_assistant(ts, {"type": "text", "text": summary})
            else:
                emit_assistant(ts, {"type": "thinking", "thinking": summary,
                                    "signature": ""})

        elif pt in ("custom_tool_call", "function_call"):
            name = p.get("name", "tool")
            call_id = p.get("call_id") or p.get("id") or "call_" + uuid.uuid4().hex[:20]
            if pt == "function_call":
                raw = p.get("arguments", "")
                try:
                    tool_input = json.loads(raw) if raw else {}
                    if not isinstance(tool_input, dict):
                        tool_input = {"arguments": tool_input}
                except json.JSONDecodeError:
                    tool_input = {"arguments": raw}
            else:
                # custom_tool_call 的 input 是自由格式字符串(如 JS 代码)
                tool_input = {"input": p.get("input", "")}
            emit_assistant(ts, {"type": "tool_use", "id": call_id,
                                "name": name, "input": tool_input})

        elif pt in ("custom_tool_call_output", "function_call_output"):
            call_id = p.get("call_id") or ""
            text = content_to_text(p.get("output"))
            emit_user(ts, [{"tool_use_id": call_id, "type": "tool_result",
                            "content": text}], is_human=False)

    if not out:
        sys.exit("没有可转换的对话内容: %s" % src)

    # 会话标题, 显示在 Claude 的历史会话列表里
    if title:
        out.append({"type": "custom-title", "customTitle": title,
                    "sessionId": session_id})

    if out_path is None:
        out_path = os.path.splitext(src)[0] + ".claude.jsonl"
    write_jsonl(out_path, out, overwrite=on_conflict == "overwrite")

    n_user = sum(1 for r in out if r["type"] == "user" and isinstance(r["message"]["content"], str))
    print("Codex -> Claude 转换完成")
    print("  来源: %s" % src)
    print("  输出: %s" % out_path)
    print("  记录: %d 条 (人类消息 %d 条), cwd=%s" % (len(out), n_user, cwd))
    if install and _is_within(out_path, CLAUDE_PROJECTS_DIR):
        print("  已安装到 Claude 项目目录, 在 %s 下运行 claude 后可在历史会话中恢复" % cwd)
        reg_title = title or (first_user_text or "imported from codex"
                              ).strip().splitlines()[0][:60]
        if register_claude_desktop(session_id, reg_title, cwd, n_user):
            print("  已注册 Claude 桌面端, 重启桌面应用后在历史列表可见")
    return out_path


def register_claude_desktop(session_id, title, cwd, human_turns):
    """注册进 Claude 桌面应用的会话列表 (尽力而为, 重启应用后生效).

    桌面应用的历史列表只读 %APPDATA%/Claude/claude-code-sessions/<org>/<user>/
    下的 local_*.json 条目。参照已有条目做模板; 找不到模板时跳过
    (未安装桌面版, 或字段集无从得知)。同一 CLI 会话重复注册时更新原条目。
    """
    root = CLAUDE_DESKTOP_DIR
    if not root or not os.path.isdir(root):
        return False
    try:
        candidates = glob.glob(os.path.join(root, "*", "*", "local_*.json"))
        if not candidates:
            return False
        by_dir = {}
        for p in candidates:
            by_dir.setdefault(os.path.dirname(p), []).append(p)
        target_dir, entries = max(by_dir.items(), key=lambda kv: len(kv[1]))
        out_file = None
        entry = None
        for p in entries:  # 已注册过同一 CLI 会话 -> 更新原条目
            try:
                with open(p, encoding="utf-8") as f:
                    existing = json.load(f)
            except (OSError, json.JSONDecodeError):
                continue
            if existing.get("cliSessionId") == session_id:
                entry, out_file = existing, p
                break
        if entry is None:
            template_path = max(entries, key=os.path.getmtime)
            with open(template_path, encoding="utf-8") as f:
                entry = json.load(f)
            entry["sessionId"] = "local_" + str(uuid.uuid4())
        now_ms = int(datetime.now(timezone.utc).timestamp() * 1000)
        entry.update({
            "cliSessionId": session_id,
            "cwd": cwd, "originCwd": cwd,
            "title": title, "titleSource": "user",
            "createdAt": now_ms, "lastActivityAt": now_ms,
            "lastFocusedAt": now_ms,
            "isArchived": False,
            "completedTurns": human_turns,
            "sessionPermissionUpdates": [],  # 不继承模板会话的权限授权
        })
        if out_file is None:
            out_file = os.path.join(target_dir, entry["sessionId"] + ".json")
        with open(out_file, "w", encoding="utf-8") as f:
            json.dump(entry, f, ensure_ascii=False)
        return True
    except (OSError, json.JSONDecodeError) as exc:
        print("  警告: 未能注册 Claude 桌面端 (%s)" % exc)
        return False


