def _win_extended(path):
    """Codex 在 Windows 上以 \\\\?\\ 前缀存路径"""
    if os.name != "nt" or path.startswith("\\\\?\\"):
        return path
    return "\\\\?\\" + path


def register_codex_thread(session_id, title, cwd, rollout_path, preview, start_ts):
    """注册进 Codex 桌面端读取的 state_5.sqlite threads 表 (尽力而为).

    只写 session_index.jsonl 的话, 新版 Codex 桌面端的历史列表看不到会话;
    列表实际读取的是 threads 表。参考已有行做模板, 缺库/缺表时静默跳过。
    """
    import sqlite3
    db = os.path.join(HOME, ".codex", "state_5.sqlite")
    if not os.path.exists(db):
        return False
    try:
        conn = sqlite3.connect(db, timeout=30)
        conn.row_factory = sqlite3.Row
        try:
            cols = {r["name"] for r in conn.execute("PRAGMA table_info(threads)")}
            if not cols:
                return False
            row = conn.execute(
                "SELECT * FROM threads WHERE id <> ? ORDER BY updated_at_ms DESC LIMIT 1",
                (session_id,)).fetchone()
            tmpl = dict(row) if row is not None else {}
            try:
                dt = datetime.fromisoformat(start_ts.replace("Z", "+00:00"))
                created_ms = int(dt.timestamp() * 1000)
            except ValueError:
                created_ms = int(datetime.now(timezone.utc).timestamp() * 1000)
            now = datetime.now(timezone.utc)
            now_s, now_ms = int(now.timestamp()), int(now.timestamp() * 1000)
            values = {
                "id": session_id,
                "rollout_path": _win_extended(rollout_path),
                "created_at": created_ms // 1000,
                "updated_at": now_s,
                "source": tmpl.get("source") or "cli",
                "model_provider": tmpl.get("model_provider") or "anthropic",
                "cwd": _win_extended(cwd),
                "title": title,
                "sandbox_policy": tmpl.get("sandbox_policy") or '{"type":"read-only"}',
                "approval_mode": tmpl.get("approval_mode") or "on-request",
                "tokens_used": 0,
                "has_user_event": 1,
                "archived": 0,
                "cli_version": "session-convert",
                "first_user_message": preview,
                "memory_mode": tmpl.get("memory_mode") or "enabled",
                "model": tmpl.get("model"),
                "created_at_ms": created_ms,
                "updated_at_ms": now_ms,
                "thread_source": "user",
                "preview": preview[:1000],
                "recency_at": now_s,
                "recency_at_ms": now_ms,
                "history_mode": tmpl.get("history_mode") or "legacy",
            }
            usable = {k: v for k, v in values.items() if k in cols}
            exists = conn.execute("SELECT 1 FROM threads WHERE id = ?",
                                  (session_id,)).fetchone() is not None
            if exists:
                sets = ", ".join('"%s" = ?' % k for k in usable if k != "id")
                conn.execute("UPDATE threads SET %s WHERE id = ?" % sets,
                             [v for k, v in usable.items() if k != "id"] + [session_id])
            else:
                names = list(usable)
                conn.execute(
                    "INSERT INTO threads (%s) VALUES (%s)"
                    % (", ".join('"%s"' % n for n in names),
                       ", ".join("?" for _ in names)),
                    [usable[n] for n in names])
            conn.commit()
            return True
        finally:
            conn.close()
    except sqlite3.Error as exc:
        print("  警告: 未能写入 Codex 状态数据库 (%s), 桌面端列表可能看不到该会话" % exc)
        return False


def claude_to_codex(src, out_path=None, install=True, on_conflict="skip"):
    records = read_jsonl(src)

    conv = [r for r in records if r.get("type") in ("user", "assistant")
            and not r.get("isSidechain") and not r.get("isMeta")]
    if not conv:
        sys.exit("没有可转换的对话内容: %s" % src)

    first = conv[0]
    cwd = first.get("cwd", os.getcwd())
    session_id = first.get("sessionId") or str(uuid.uuid4())
    start_ts = first.get("timestamp") or now_iso()

    if install and out_path is None:
        try:
            dt = datetime.fromisoformat(start_ts.replace("Z", "+00:00"))
        except ValueError:
            dt = datetime.now(timezone.utc)
        day_dir = os.path.join(CODEX_SESSIONS_DIR, dt.strftime("%Y"),
                               dt.strftime("%m"), dt.strftime("%d"))
        out_path = os.path.join(
            day_dir, "rollout-%s-%s.jsonl" % (
                dt.strftime("%Y-%m-%dT%H-%M-%S"), session_id))
        out_path, fork_id, skipped = _resolve_output_conflict(
            out_path, on_conflict, lambda: str(uuid.uuid4()),
            lambda target_id: os.path.join(
                day_dir, "rollout-%s-%s.jsonl" % (
                    dt.strftime("%Y-%m-%dT%H-%M-%S"), target_id)))
        if skipped:
            return out_path
        if fork_id:
            session_id = fork_id
    elif out_path is not None:
        out_path, fork_id, skipped = _resolve_output_conflict(
            out_path, on_conflict, lambda: str(uuid.uuid4()))
        if skipped:
            return out_path
        if fork_id:
            session_id = fork_id

    out = []
    first_user_text = None
    img_count = 0
    n_images = 0

    def wrap(ts, rtype, payload):
        out.append({"timestamp": ts, "type": rtype, "payload": payload})

    def save_image(source):
        """把 base64 图片落盘, 供 Codex 界面显示 (模型上下文另走 data URL)"""
        nonlocal img_count
        img_count += 1
        media = source.get("media_type", "image/png")
        ext = {"image/png": ".png", "image/jpeg": ".jpg",
               "image/gif": ".gif", "image/webp": ".webp"}.get(media, ".png")
        img_dir = os.path.join(HOME, ".codex", "bridge-images", session_id)
        os.makedirs(img_dir, exist_ok=True)
        path = os.path.join(img_dir, "img-%03d%s" % (img_count, ext))
        with open(path, "wb") as f:
            f.write(base64.b64decode(source.get("data", "")))
        return path

    # 会话头
    wrap(start_ts, "session_meta", {
        "session_id": session_id, "id": session_id, "timestamp": start_ts,
        "cwd": cwd, "originator": "session_convert",
        "cli_version": "converted-from-claude", "source": "import",
        "thread_source": "user", "model_provider": "anthropic",
    })

    for rec in conv:
        ts = rec.get("timestamp") or now_iso()
        msg = rec.get("message", {})
        content = msg.get("content")

        if rec["type"] == "user":
            if isinstance(content, str):
                if content.lstrip().startswith(CLAUDE_NOISE_PREFIXES):
                    continue
                if first_user_text is None:
                    first_user_text = content
                wrap(ts, "event_msg", {
                    "type": "user_message", "message": content,
                    "images": [], "local_images": [], "audio": [],
                    "local_audio": [], "text_elements": [],
                })
                wrap(ts, "response_item", {
                    "type": "message",
                    "id": "msg_" + uuid.uuid4().hex[:24],
                    "role": "user",
                    "content": [{"type": "input_text", "text": content}],
                })
            elif isinstance(content, list):
                texts, images = [], []
                for block in content:
                    if not isinstance(block, dict):
                        continue
                    bt = block.get("type")
                    if bt == "tool_result":
                        result = block.get("content", "")
                        if isinstance(result, list):
                            result = "".join(
                                b.get("text", "") for b in result
                                if isinstance(b, dict))
                        wrap(ts, "response_item", {
                            "type": "function_call_output",
                            "id": "fco_" + uuid.uuid4().hex[:24],
                            "call_id": block.get("tool_use_id", ""),
                            "output": [{"type": "input_text", "text": str(result)}],
                        })
                    elif bt == "text" and block.get("text", "").strip():
                        texts.append(block["text"])
                    elif bt == "image" and isinstance(block.get("source"), dict) \
                            and block["source"].get("type") == "base64":
                        images.append(block["source"])
                if texts or images:
                    # 用户"图片+文字"消息: event 让 Codex 界面显示,
                    # response_item 用 data URL 让模型上下文携带图片本体
                    n_images += len(images)
                    joined = "\n\n".join(texts)
                    local_paths = [save_image(s) for s in images] if install else []
                    wrap(ts, "event_msg", {
                        "type": "user_message", "message": joined,
                        "images": [], "local_images": local_paths,
                        "audio": [], "local_audio": [], "text_elements": [],
                    })
                    item_content = [
                        {"type": "input_image",
                         "image_url": "data:%s;base64,%s" % (
                             s.get("media_type", "image/png"), s.get("data", ""))}
                        for s in images]
                    if joined:
                        item_content.append({"type": "input_text", "text": joined})
                    wrap(ts, "response_item", {
                        "type": "message",
                        "id": "msg_" + uuid.uuid4().hex[:24],
                        "role": "user",
                        "content": item_content,
                    })

        else:  # assistant
            for block in (content or []):
                if not isinstance(block, dict):
                    continue
                bt = block.get("type")
                if bt == "text" and block.get("text", "").strip():
                    wrap(ts, "event_msg", {
                        "type": "agent_message", "message": block["text"],
                        "phase": "final_answer",
                    })
                    wrap(ts, "response_item", {
                        "type": "message",
                        "id": "msg_" + uuid.uuid4().hex[:24],
                        "role": "assistant",
                        "content": [{"type": "output_text",
                                     "text": block["text"]}],
                        "phase": "final_answer",
                    })
                elif bt == "thinking" and block.get("thinking", "").strip():
                    wrap(ts, "response_item", {
                        "type": "reasoning",
                        "id": "rs_" + uuid.uuid4().hex[:24],
                        "summary": [{"type": "summary_text",
                                     "text": block["thinking"]}],
                    })
                elif bt == "tool_use":
                    wrap(ts, "response_item", {
                        "type": "function_call",
                        "id": "fc_" + uuid.uuid4().hex[:24],
                        "name": block.get("name", "tool"),
                        "arguments": json.dumps(block.get("input", {}),
                                                ensure_ascii=False),
                        "call_id": block.get("id", ""),
                    })

    if out_path is None:
        out_path = os.path.splitext(src)[0] + ".codex.jsonl"
    write_jsonl(out_path, out, overwrite=on_conflict == "overwrite")

    # 追加到 codex 会话索引 + 注册桌面端状态数据库, 让它出现在历史列表里
    registered = False
    if install and _is_within(out_path, CODEX_SESSIONS_DIR):
        title = (first_user_text or "imported from claude").strip()
        title = title.splitlines()[0][:60]
        upsert_codex_index(session_id, title)
        preview = (first_user_text or title).strip()
        registered = register_codex_thread(
            session_id, title, cwd, out_path, preview, start_ts)

    print("Claude -> Codex 转换完成")
    print("  来源: %s" % src)
    print("  输出: %s" % out_path)
    print("  记录: %d 条%s, cwd=%s" % (
        len(out), ", 图片 %d 张" % n_images if n_images else "", cwd))
    if install and _is_within(out_path, CODEX_SESSIONS_DIR):
        print("  已安装到 Codex 会话目录并写入索引%s"
              % (", 已注册桌面端数据库" if registered else ""))
    return out_path


